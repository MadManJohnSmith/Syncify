    #[test]
    fn cleaning_is_idempotent() {
        let input = "Song Title\n[ar:Artist]\nProvided to YouTube by Label\n\n[00:05.00]First";
        let once = strip_lyrics_header(input);
        let twice = strip_lyrics_header(&once);
        assert_eq!(once, twice);
        // The title line is ambiguous, so it stays; the rest of the header goes.
        assert_eq!(once, "Song Title\n[00:05.00]First");
    }

    #[test]
    fn report_indexes_point_at_the_input_lines() {
        let input = "Provided to YouTube by Label\n\n[00:05.00]First";
        let report = clean_lyrics_header(input, &opts_default());
        assert_eq!(report.removed[0].index, 0);
        assert_eq!(report.removed[1].index, 1);
        assert_eq!(report.removed[1].reason.rule_id(), "header_separator");
    }

    #[test]
    fn documents_that_strip_lrc_timestamps_alone_leaves_the_header() {
        // `strip_lrc_timestamps` is render-time code and is deliberately NOT
        // changed: it only knows about `[mm:ss.xx]`. This test pins that behaviour
        // so that wiring the boundary cleaner in has to be a conscious change.
        let input = "[ti:Song]\n[ar:Artist]\n[00:05.00]First line";
        assert_eq!(
            strip_lrc_timestamps(input),
            "[ti:Song]\n[ar:Artist]\nFirst line"
        );
        assert_eq!(strip_lyrics_header(input), "[00:05.00]First line");
    }

    #[test]
    fn boundary_cleaner_is_composable_with_render_time_stripping() {
        let input = "[ti:Song]\n[ar:Artist]\n[00:05.00] <00:05.00>First <00:06.00>line";
        let boundary = strip_lyrics_header(input);
        assert_eq!(boundary, "[00:05.00] <00:05.00>First <00:06.00>line");
        assert_eq!(strip_lrc_timestamps(&boundary), "First line");
    }
