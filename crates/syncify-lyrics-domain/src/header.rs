    #[test]
    fn scan_window_is_parametrizable() {
        let filler = (0..DEFAULT_MAX_LEADING_LINES)
            .map(|i| format!("line {i}"))
            .collect::<Vec<_>>()
            .join("\n");
        let input = format!("{filler}\n[ti:Song]\nlast");

        let report = clean_lyrics_header(&input, &opts_default());
        assert!(
            report.is_unchanged(),
            "tag sits on line {DEFAULT_MAX_LEADING_LINES}"
        );

        let mut wide = opts_default();
        wide.max_leading_lines = 40;
        let cleaned = strip_lyrics_header_with(&input, &wide);
        assert!(!cleaned.contains("[ti:Song]"));
        assert!(cleaned.starts_with("line 0"));
        assert!(cleaned.ends_with("last"));
    }

